def dialogue_prompt(*, author_is_owner: bool, is_group: bool, spontaneous: bool) -> str:
    place = 'Группа Telegram.' if is_group else 'Личная переписка.'
    author = ('Автор текущей реплики — подтверждённый создатель.'
              if author_is_owner else 'Автор текущей реплики — обычный участник.')
    addressing = OWNER_ADDRESS if author_is_owner else PARTICIPANT_ADDRESS
    prompt = f'{PERSONA}\nКонтекст приложения: {place} {author}\n{addressing}'
    if spontaneous:
        prompt += '\nТы сама ненавязчиво присоединилась к разговору. Ответь коротко и по теме.'
    return f'{prompt}\n\n{DIALOGUE_STYLE}'


def speaker_label(name: str) -> str:
    """Keep names on one line and inside their own prompt delimiters."""
    normalized = ' '.join(name.split()).replace('[', '［').replace(']', '］')
    if normalized.casefold() == 'создатель':
        return 'Собеседник'
    return normalized[:60] or 'Собеседник'
